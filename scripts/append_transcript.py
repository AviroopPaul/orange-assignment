#!/usr/bin/env python3
"""Append new Claude Code conversation entries to docs/transcript.md.

Reads this project's session logs, which keep the full history even after compaction. Safe to run
any time: docs/transcript.state.json records the last entry written for each session, so only new
entries are added. Usage: make transcript
"""

import json
import os
import re
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / "docs" / "transcript.md"
STATE = REPO / "docs" / "transcript.state.json"
SESSIONS = Path.home() / ".claude" / "projects" / str(REPO).replace("/", "-")

MAX_TOOL_INPUT_CHARS = 1500
MAX_TOOL_RESULT_CHARS = 1500

HEADER = """\
# AI assistant transcript

A running record of the Claude Code sessions used to build this project. This is an assignment
deliverable, and a reference that survives context compaction.

- **Generated by:** `make transcript`, which only appends. Do not edit it by hand.
- **Left out:** thinking, images, and instruction blocks injected by the app.
- **Shortened:** long tool inputs and results are cut, and marked where they are.
- **Masked:** API keys and phone numbers.
"""

_INJECTED = re.compile(
    r"<(system-reminder|task-notification|side-sessions-event|ci-monitor-event)\b.*?</\1>",
    re.DOTALL,
)
_GOOGLE_KEY = re.compile(r"AIza[0-9A-Za-z_-]{20,}")
_PHONE = re.compile(r"\+\d{1,3}[-\s]?\d{6,12}|(?<![\d-])[6-9]\d{9}(?!\d)")


def clean(text: str) -> str:
    """Drop injected blocks and mask secrets. Runs on everything written to the file."""
    text = _PHONE.sub("[phone]", _GOOGLE_KEY.sub("[api-key]", _INJECTED.sub("", text)))
    key = os.environ.get("GOOGLE_API_KEY")
    return (text.replace(key, "[api-key]") if key else text).strip()


def shorten(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return f"{text[:limit]}\n… [{len(text) - limit} more characters not shown]"


def fence(text: str) -> str:
    """A code fence longer than any backtick run inside, so content cannot break out of it."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}\n{text}\n{ticks}"


def tool_input(name: str, data: dict) -> str:
    if name == "Bash":
        summary, body = data.get("description", ""), data.get("command", "")
    elif name in ("Write", "Read"):
        summary, body = data.get("file_path", ""), data.get("content", "")
    elif name == "Edit":
        summary = data.get("file_path", "")
        body = f"--- old\n{data.get('old_string', '')}\n--- new\n{data.get('new_string', '')}"
    else:
        summary, body = "", json.dumps(data, ensure_ascii=False, indent=1)

    title = f"**Tool: {name}**" + (f" ({clean(summary)})" if summary else "")
    body = clean(body)
    return f"{title}\n\n{fence(shorten(body, MAX_TOOL_INPUT_CHARS))}" if body else title


def result_text(content: object) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, dict) and item.get("type") == "text":
                parts.append(item.get("text", ""))
            elif isinstance(item, dict):
                parts.append(f"[{item.get('type', 'content')} not shown]")
        return "\n".join(parts)
    return ""


def render(entry: dict) -> str:
    """One log entry as Markdown, or an empty string if nothing in it belongs in the record."""
    message = entry.get("message") or {}
    content = message.get("content")
    blocks = [{"type": "text", "text": content}] if isinstance(content, str) else content or []

    chunks = []
    for block in blocks:
        kind = block.get("type") if isinstance(block, dict) else None
        if kind == "text":
            text = clean(block.get("text", ""))
            if not text:
                continue
            if entry.get("isCompactSummary"):
                chunks.append(f"**Context was compacted here. Summary:**\n\n{text}")
            else:
                chunks.append(f"**{'You' if entry['type'] == 'user' else 'Claude'}:**\n\n{text}")
        elif kind == "tool_use":
            chunks.append(tool_input(block.get("name", "tool"), block.get("input") or {}))
        elif kind == "tool_result":
            text = clean(result_text(block.get("content")))
            if text:
                label = "Result (error)" if block.get("is_error") else "Result"
                chunks.append(f"{label}:\n\n{fence(shorten(text, MAX_TOOL_RESULT_CHARS))}")
    return "\n\n".join(chunks)


def session_entries(path: Path) -> list[dict]:
    entries = []
    with path.open(encoding="utf-8") as log:
        for line in log:
            try:
                entry = json.loads(line)
            except ValueError:
                continue
            is_turn = entry.get("type") in ("user", "assistant") and entry.get("uuid")
            if is_turn and not entry.get("isSidechain") and not entry.get("isMeta"):
                entries.append(entry)
    return entries


def new_entries(entries: list[dict], last_uuid: str | None) -> list[dict]:
    if last_uuid is None:
        return entries
    for index, entry in enumerate(entries):
        if entry["uuid"] == last_uuid:
            return entries[index + 1 :]
    # The marker should always be found. Stop rather than write the whole session twice.
    raise SystemExit(f"Last exported entry {last_uuid} is missing, so nothing was appended.")


def main() -> None:
    state: dict[str, str] = json.loads(STATE.read_text()) if STATE.exists() else {}
    if not OUTPUT.exists():
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(HEADER, encoding="utf-8")

    added = 0
    logs = sorted(SESSIONS.glob("*.jsonl"), key=lambda path: path.stat().st_mtime)
    with OUTPUT.open("a", encoding="utf-8") as out:
        for log in logs:
            session = log.stem
            entries = session_entries(log)
            fresh = new_entries(entries, state.get(session))
            if not fresh:
                continue
            if session not in state:
                started = str(fresh[0].get("timestamp", ""))[:10]
                out.write(f"\n---\n\n## Session {session[:8]} (started {started})\n")
            for entry in fresh:
                text = render(entry)
                if text:
                    out.write(f"\n{text}\n")
                    added += 1
            state[session] = fresh[-1]["uuid"]

    STATE.write_text(json.dumps(state, indent=2) + "\n")
    print(f"{datetime.now():%Y-%m-%d %H:%M}: appended {added} entries to {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
