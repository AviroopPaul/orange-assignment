"""Writes the eval table. It holds only what this run measured, in three formats."""

import csv
import json
from dataclasses import asdict, dataclass
from pathlib import Path

from evals.invariants import DESCRIPTIONS
from evals.scenario import CATEGORIES

PASS, FAIL, ERROR = "PASS", "FAIL", "ERROR"
COLUMNS = (
    "id",
    "category",
    "scenario",
    "expected",
    "actual",
    "result",
    "invariants",
    "seconds",
    "notes",
)


@dataclass
class Row:
    id: str
    category: str
    scenario: str
    expected: str
    actual: str
    result: str
    invariants: str
    seconds: float
    notes: str


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def summary(rows: list[Row]) -> dict:
    return {
        "total": len(rows),
        "passed": sum(row.result == PASS for row in rows),
        "failed": sum(row.result == FAIL for row in rows),
        "errors": sum(row.result == ERROR for row in rows),
    }


def _invariant_failures(rows: list[Row], name: str) -> list[str]:
    return [row.id for row in rows if f"{name}:" in row.invariants]


def uncovered_categories(rows: list[Row]) -> list[str]:
    seen = {row.category for row in rows}
    return [category for category in CATEGORIES if category not in seen]


def write_markdown(path: Path, rows: list[Row], started_at: str, partial: bool) -> None:
    totals = summary(rows)
    lines = [
        "# Eval results",
        "",
        "Generated by `make evals`. Do not edit by hand.",
        "",
        f"- **Run started:** {started_at}",
        f"- **Result:** {totals['passed']} of {totals['total']} passed, "
        f"{totals['failed']} failed, {totals['errors']} errors.",
    ]
    if partial:
        lines.append("- **Partial run:** only some scenarios were chosen.")
    lines += [
        "- **Offline:** the run has no route to the internet. A preflight check proves it.",
        "- **Known limit:** a scripted model tests our code's rules, not Gemini's judgement.",
        "",
        "## Scenarios",
        "",
        "| ID | Scenario | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        notes = row.notes if row.invariants == "all held" else f"{row.invariants}. {row.notes}"
        lines.append(
            f"| {row.id} | {_cell(row.scenario)} | {_cell(row.expected)} "
            f"| {_cell(row.actual)} | **{row.result}** | {_cell(notes)} |"
        )
    lines += [
        "",
        "## Invariants",
        "",
        "Checked after every scenario, by reading the databases.",
        "",
        "| ID | Invariant | Scenarios checked | Violations |",
        "|---|---|---|---|",
    ]
    for name, text in DESCRIPTIONS.items():
        failed = _invariant_failures(rows, name)
        lines.append(f"| {name} | {text} | {len(rows)} | {', '.join(failed) or 'none'} |")
    lines += ["", "## Coverage of the brief", "", "| Area | Scenarios |", "|---|---|"]
    for category in CATEGORIES:
        ids = [row.id for row in rows if row.category == category]
        lines.append(f"| {category} | {', '.join(ids) or 'NONE'} |")
    path.write_text("\n".join(lines) + "\n")


def write_json(path: Path, rows: list[Row], started_at: str, partial: bool) -> None:
    path.write_text(
        json.dumps(
            {
                "started_at": started_at,
                "partial": partial,
                "summary": summary(rows),
                "uncovered_categories": uncovered_categories(rows),
                "invariants": {
                    name: {"text": text, "violated_in": _invariant_failures(rows, name)}
                    for name, text in DESCRIPTIONS.items()
                },
                "scenarios": [asdict(row) for row in rows],
            },
            indent=2,
        )
        + "\n"
    )


def write_csv(path: Path, rows: list[Row]) -> None:
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(asdict(row) for row in rows)


def write_all(directory: Path, rows: list[Row], started_at: str, partial: bool) -> None:
    """A run of chosen scenarios gets its own files, so it can never replace the full table."""
    directory.mkdir(parents=True, exist_ok=True)
    stem = "results.partial" if partial else "results"
    write_markdown(directory / f"{stem}.md", rows, started_at, partial)
    write_json(directory / f"{stem}.json", rows, started_at, partial)
    write_csv(directory / f"{stem}.csv", rows)
